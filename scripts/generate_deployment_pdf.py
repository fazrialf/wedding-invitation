    # ── COVER PAGE ─────────────────────────────────────────
    pdf.add_page()
    pdf.set_y(50)

    # Decorative top bar
    pdf.set_fill_color(*C_PRIMARY)
    pdf.rect(0, 0, 210, 5, style="F")
    pdf.set_fill_color(*C_ACCENT)
    pdf.rect(0, 5, 210, 2, style="F")

    # Title
    pdf.set_font("DejaVu", "B", 28)
    pdf.set_text_color(*C_PRIMARY)
    pdf.cell(0, 14, "Wedding Digital Invitation", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    pdf.set_font("DejaVu", "", 14)
    pdf.set_text_color(*C_ACCENT)
    pdf.cell(0, 10, "Deployment Guide", align="C", new_x="LMARGIN", new_y="NEXT")

