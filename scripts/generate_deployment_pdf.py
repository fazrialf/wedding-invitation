    pdf.data_table(
        ["Service", "Container", "Port", "Purpose"],
        [
            ["nginx", "wedding_nginx", "8081->80", "Reverse proxy"],
            ["frontend", "wedding_frontend", "3000 (int)", "Next.js standalone server"],
            ["backend", "wedding_backend", "4000->4000", "Express.js API server"],
            ["postgres", "wedding_postgres", "5432->5432", "PostgreSQL 16 database"],
            ["redis", "wedding_redis", "6379->6379", "Redis 7 cache"],
        ],
        col_widths=[22, 35, 30, 83]
    )

