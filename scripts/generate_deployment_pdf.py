            ["NODE_ENV", "Backend", "production", "Node environment"],
            ["DB_HOST", "Backend", "postgres", "PostgreSQL hostname (Docker svc)"],
            ["DB_PORT", "Backend", "5432", "PostgreSQL port"],
            ["DB_NAME", "Backend", "wedding", "Database name"],
