    pdf.ln(8)

    # Subtitle
    pdf.set_font("DejaVu", "I", 11)
    pdf.set_text_color(*C_DARK)
    pdf.multi_cell(0, 6, "Complete guide for deploying the wedding invitation\nplatform on a fresh server instance from GitHub.", align="C")
    pdf.ln(15)

