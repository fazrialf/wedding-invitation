#!/usr/bin/env python3
"""
Generate the Wedding Invitation Deployment Guide PDF.
Uses fpdf2 with DejaVuSans fonts (full Unicode support).
"""

from fpdf import FPDF
import os

# ── Fonts ──────────────────────────────────────────────────
FONT_DIR = "/usr/share/fonts/truetype/dejavu"
REGULAR   = os.path.join(FONT_DIR, "DejaVuSans.ttf")
BOLD      = os.path.join(FONT_DIR, "DejaVuSans-Bold.ttf")
ITALIC    = os.path.join(FONT_DIR, "DejaVuSans-Oblique.ttf")
BOLD_IT   = os.path.join(FONT_DIR, "DejaVuSans-BoldOblique.ttf")
MONO      = os.path.join(FONT_DIR, "DejaVuSansMono.ttf")
MONO_BOLD = os.path.join(FONT_DIR, "DejaVuSansMono-Bold.ttf")

# ── Colors ─────────────────────────────────────────────────
C_PRIMARY   = (139, 69, 19)     # Saddle brown — wedding theme
C_ACCENT    = (205, 133, 63)    # Peru / warm accent
C_DARK      = (51, 51, 51)      # Body text
C_LIGHT_BG  = (250, 245, 238)   # Cream background
C_CODE_BG   = (245, 240, 233)   # Slightly darker cream for code
C_TABLE_HDR = (139, 69, 19)     # Header row
C_TABLE_ROW = (250, 245, 238)   # Alt row
C_TABLE_ALT = (255, 250, 243)   # Alt row 2
C_BORDER    = (200, 180, 160)   # Soft border
C_GREEN     = (34, 139, 34)
C_RED       = (178, 34, 34)
C_BLUE      = (30, 90, 160)

class DeploymentPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=25)
        self.set_margins(20, 25, 20)
        self.add_font("DejaVu", "", REGULAR)
        self.add_font("DejaVu", "B", BOLD)
        self.add_font("DejaVu", "I", ITALIC)
        self.add_font("DejaVu", "BI", BOLD_IT)
        self.add_font("Mono", "", MONO)
        self.add_font("Mono", "B", MONO_BOLD)

    def header(self):
        """Page header — skip on cover page."""
        if self.page_no() == 1:
            return
        self.set_font("DejaVu", "I", 8)
        self.set_text_color(*C_BORDER)
        self.cell(0, 8, "Wedding Invitation — Deployment Guide", align="L")
        self.cell(0, 8, f"Page {self.page_no() - 1}", align="R", new_x="RIGHT", new_y="NEXT")
        self.set_draw_color(*C_BORDER)
        self.line(20, 23, 190, 23)
        self.ln(5)

    def footer(self):
        """Page footer."""
        if self.page_no() == 1:
            return
        self.set_y(-18)
        self.set_font("DejaVu", "I", 7)
        self.set_text_color(*C_BORDER)
        self.cell(0, 5, "Generated by Hermes Agent — June 2026", align="C")

    # ── Helpers ────────────────────────────────────────────

    def section_title(self, num, title):
        """Major section title with colored bar."""
        self.ln(4)
        self.set_fill_color(*C_PRIMARY)
        self.set_text_color(255, 255, 255)
        self.set_font("DejaVu", "B", 13)
        self.cell(0, 9, f"  {num}. {title}", fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(4)
        self.set_text_color(*C_DARK)

    def subsection_title(self, title):
        """Subsection heading."""
        self.ln(2)
        self.set_font("DejaVu", "B", 11)
        self.set_text_color(*C_PRIMARY)
        self.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(*C_DARK)
        self.ln(1)

    def body_text(self, text):
        """Regular paragraph text."""
        self.set_font("DejaVu", "", 10)
        self.set_text_color(*C_DARK)
        self.multi_cell(0, 6, text)
        self.ln(2)

    def body_text_html(self, segments):
        """Write text with mixed formatting. segments = [(text, style), ...]
        style: '' normal, 'B' bold, 'I' italic, 'BI' bold-italic"""
        self.set_text_color(*C_DARK)
        for text, style in segments:
            self.set_font("DejaVu", style, 10)
            self.write(6, text)

    def bullet(self, text, indent=0):
        """Bullet point."""
        x = 20 + indent
        self.set_x(x)
        self.set_font("DejaVu", "", 10)
        self.set_text_color(*C_ACCENT)
        self.cell(5, 6, "->", new_x="RIGHT")
        self.set_text_color(*C_DARK)
        self.multi_cell(0, 6, text)
        self.ln(0.5)

    def numbered(self, num, text, indent=0):
        """Numbered list item."""
        x = 20 + indent
        self.set_x(x)
        self.set_font("DejaVu", "B", 10)
        self.set_text_color(*C_PRIMARY)
        self.cell(7, 6, f"{num}.", new_x="RIGHT")
        self.set_font("DejaVu", "", 10)
        self.set_text_color(*C_DARK)
        self.multi_cell(0, 6, text)
        self.ln(0.5)

    def code_block(self, code):
        """Monospace code block with background."""
        self.ln(1)
        # Calculate height
        lines = code.strip().split("\n")
        line_h = 5
        total_h = len(lines) * line_h + 4

        # Check if we need a page break
        if self.get_y() + total_h > self.h - 25:
            self.add_page()

        x = self.get_x()
        y = self.get_y()

        # Background
        self.set_fill_color(*C_CODE_BG)
        self.set_draw_color(*C_BORDER)
        # Use rect for background
        self.rect(x, y, 170, total_h, style="DF")

        # Code text
        self.set_xy(x + 3, y + 2)
        self.set_font("Mono", "", 8.5)
        self.set_text_color(60, 60, 60)
        for line in lines:
            self.set_x(x + 3)
            self.cell(0, line_h, line, new_x="LMARGIN", new_y="NEXT")

        self.ln(3)
        self.set_text_color(*C_DARK)

    def info_box(self, text, box_type="info"):
        """Colored callout box. box_type: info, warning, danger, success"""
        colors = {
            "info":    (230, 240, 250),
            "warning": (255, 248, 220),
            "danger":  (255, 235, 230),
            "success": (230, 245, 230),
        }
        borders = {
            "info":    (30, 90, 160),
            "warning": (200, 150, 0),
            "danger":  (178, 34, 34),
            "success": (34, 139, 34),
        }
        bg = colors.get(box_type, colors["info"])
        bd = borders.get(box_type, borders["info"])

        self.ln(1)
        lines = text.split("\n")
        total_h = len(lines) * 6 + 6

        if self.get_y() + total_h > self.h - 25:
            self.add_page()

        x = self.get_x()
        y = self.get_y()

        # Background bar on left
        self.set_fill_color(*bd)
        self.rect(x, y, 2, total_h, style="F")
        self.set_fill_color(*bg)
        self.rect(x + 2, y, 168, total_h, style="F")

        self.set_xy(x + 6, y + 3)
        self.set_font("DejaVu", "", 9.5)
        self.set_text_color(*C_DARK)
        for line in lines:
            self.set_x(x + 6)
            self.multi_cell(162, 6, line)
        self.ln(2)
        self.set_text_color(*C_DARK)

    def data_table(self, headers, rows, col_widths=None):
        """Simple table with header and rows."""
        if col_widths is None:
            avail = 170
            col_widths = [avail / len(headers)] * len(headers)

        # Check space
        needed = (len(rows) + 1) * 7 + 2
        if self.get_y() + needed > self.h - 25:
            self.add_page()

        # Header
        self.set_font("DejaVu", "B", 9)
        self.set_fill_color(*C_TABLE_HDR)
        self.set_text_color(255, 255, 255)
        for i, h in enumerate(headers):
            self.cell(col_widths[i], 7, h, border="1", fill=True, align="C")
        self.ln()

        # Rows
        self.set_font("DejaVu", "", 8.5)
        self.set_text_color(*C_DARK)
        for r_idx, row in enumerate(rows):
            if self.get_y() + 7 > self.h - 25:
                self.add_page()
                # Re-print header
                self.set_font("DejaVu", "B", 9)
                self.set_fill_color(*C_TABLE_HDR)
                self.set_text_color(255, 255, 255)
                for i, h in enumerate(headers):
                    self.cell(col_widths[i], 7, h, border="1", fill=True, align="C")
                self.ln()
                self.set_font("DejaVu", "", 8.5)
                self.set_text_color(*C_DARK)

            bg = C_TABLE_ALT if r_idx % 2 == 0 else C_TABLE_ROW
            self.set_fill_color(*bg)
            for i, cell in enumerate(row):
                self.cell(col_widths[i], 7, cell, border="1", fill=True)
            self.ln()

        self.ln(3)
        self.set_text_color(*C_DARK)


# ═══════════════════════════════════════════════════════════
#  BUILD THE PDF
